package com.may26.dto;

public class GeneratedVocabulary {

    public String word;
    public String meaning;
    public String example;

    public GeneratedVocabulary() {
    }

    public GeneratedVocabulary(
            String word,
            String meaning,
            String example) {

        this.word = word;
        this.meaning = meaning;
        this.example = example;
    }
}